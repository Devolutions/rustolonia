using Avalonia.Projection.Ir;

namespace Avalonia.Projection.Generator;

public static class ComSourceEmitter
{
    public static IReadOnlyDictionary<string, string> Emit(ProjectionIr ir)
    {
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var type in ir.Types.Where(t => t.Kind == ProjectedTypeKind.Interface))
            files[type.Name + ".g.cs"] = EmitInterface(type);
        foreach (var @event in ir.Types
                     .SelectMany(t => t.Events)
                     .GroupBy(e => e.HandlerInterfaceName, StringComparer.Ordinal)
                     .Select(g => g.First()))
        {
            files[SimpleName(@event.HandlerInterfaceName) + ".g.cs"] = EmitEventHandler(@event);
        }
        foreach (var type in ir.Types.Where(t => t.Kind == ProjectedTypeKind.Class))
            files[type.Name + ".g.cs"] = EmitClass(ir, type);
        if (ir.Types.Any(t => t.Kind == ProjectedTypeKind.Class))
        {
            foreach (var collection in ir.Types
                         .SelectMany(t => t.Properties)
                         .Where(p => p.Kind == MarshallingKind.ComCollection)
                         .GroupBy(p => p.InterfaceName, StringComparer.Ordinal)
                         .Select(g => g.First()))
            {
                files[SimpleName(collection.InterfaceName!) + ".g.cs"] = EmitCollection(ir, collection);
            }
            foreach (var statics in ir.AttachedProperties
                         .GroupBy(p => p.StaticsInterfaceName, StringComparer.Ordinal))
            {
                files[SimpleName(statics.Key) + ".g.cs"] = EmitAttachedProperties(ir, statics.ToArray());
            }
            files["ProjectionRuntime.g.cs"] = EmitRuntime(ir);
            files["ProjectionStructs.g.cs"] = EmitGeometryStructs(ir);
            if (ir.BrushInterfaceName is not null)
                files[SimpleName(ir.BrushInterfaceName) + ".g.cs"] = EmitBrush(ir);
            if (ir.GradientBrushInterfaceName is not null)
                files[SimpleName(ir.GradientBrushInterfaceName) + ".g.cs"] = EmitGradientBrush(ir);
            if (ir.CommandInterfaceName is not null)
                files[SimpleName(ir.CommandInterfaceName) + ".g.cs"] = EmitCommand(ir);
            if (ir.TemplateInterfaceName is not null)
                files[SimpleName(ir.TemplateInterfaceName) + ".g.cs"] = EmitDataTemplate(ir);
            if (ir.ItemFilterInterfaceName is not null ||
                ir.TextFilterInterfaceName is not null)
                files["AvnFilters.g.cs"] = EmitFilters(ir);
            if (ir.ItemSelectorInterfaceName is not null ||
                ir.TextSelectorInterfaceName is not null)
                files["AvnSelectors.g.cs"] = EmitSelectors(ir);
            if (ir.PopupPlacementInterfaceName is not null)
                files["AvnPopupPlacement.g.cs"] = EmitPopupPlacement(ir);
            if (ir.AsyncPopulatorInterfaceName is not null)
                files["AvnAsyncPopulator.g.cs"] = EmitAsyncPopulator(ir);
            if (ir.NotificationInterfaceName is not null)
                files[SimpleName(ir.NotificationInterfaceName) + ".g.cs"] = EmitNotification(ir);
            files["IAvnControlFactory.g.cs"] = EmitFactory(ir);
            files["ProjectionAotRoots.g.cs"] = EmitAotRoots(ir);
        }
        return files;
    }

    public static string EmitInterface(ProjectedType type)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using System.Runtime.InteropServices.Marshalling;");
        sb.AppendLine();
        var ns = NamespaceOf(type.FullName);
        if (ns is not null)
        {
            sb.AppendLine($"namespace {ns};");
            sb.AppendLine();
        }

        sb.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]");
        if (!string.IsNullOrEmpty(type.Iid))
            sb.AppendLine($"[Guid(\"{type.Iid}\")]");

        var bases = type.BaseFullName is { } b ? $" : {SimpleName(b)}" : "";
        sb.AppendLine($"public partial interface {type.Name}{bases}");
        sb.AppendLine("{");

        foreach (var method in type.Methods)
        {
            if (method.PreserveSig)
                sb.AppendLine("    [PreserveSig]");
            sb.Append("    ");
            sb.Append(CSharpType(method.ReturnKind, null, false));
            sb.Append(' ');
            sb.Append(method.Name);
            sb.Append('(');
            sb.Append(string.Join(", ", method.Parameters.Select(FormatParameter)));
            sb.AppendLine(");");
            sb.AppendLine();
        }

        foreach (var prop in type.Properties)
        {
            sb.Append("    ");
            sb.Append(CSharpType(prop.Kind, prop.InterfaceName, false));
            sb.Append(' ');
            sb.Append(prop.Name);
            sb.Append(" { ");
            if (prop.CanRead)
                sb.Append("get; ");
            if (prop.CanWrite)
                sb.Append("set; ");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitClass(ProjectionIr ir, ProjectedType type)
    {
        var sb = Header(type);
        var bases = type.BaseFullName is { } b ? $" : {SimpleName(b)}" : "";
        sb.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]");
        sb.AppendLine($"[Guid(\"{type.Iid}\")]");
        sb.AppendLine($"public partial interface {type.Name}{bases}");
        sb.AppendLine("{");
        if (type.BaseFullName is null)
        {
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine("    int GetObjectId(out long value);");
            sb.AppendLine();
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine("    int GetLifetimeToken(out long value);");
            sb.AppendLine();
        }
        foreach (var property in type.Properties)
            EmitInterfaceProperty(sb, property);
        foreach (var method in type.Methods)
            EmitInterfaceMethod(sb, method);
        foreach (var @event in type.Events)
            EmitInterfaceEvent(sb, @event);
        sb.AppendLine("}");
        sb.AppendLine();

        var wrapperName = type.Name[1..];
        var events = Lineage(ir, type).SelectMany(t => t.Events).ToArray();
        sb.AppendLine("[GeneratedComClass]");
        sb.AppendLine($"public sealed partial class {wrapperName} : {type.Name}");
        sb.AppendLine("{");
        sb.AppendLine("    private readonly global::Avalonia.Host.Ownership.ProjectionObjectState _state;");
        sb.AppendLine($"    private global::{type.ManagedFullName} _value => _state.GetTarget<global::{type.ManagedFullName}>();");
        foreach (var @event in events)
        {
            var handler = SimpleName(@event.HandlerInterfaceName);
            sb.AppendLine($"    private readonly global::System.Collections.Generic.Dictionary<long, ({handler} Handler, global::System.Action Unsubscribe)> _{LowerFirst(@event.Name)}Subscriptions = new();");
            sb.AppendLine($"    private long _next{@event.Name}SubscriptionId;");
        }
        sb.AppendLine();
        sb.AppendLine($"    internal {wrapperName}(global::{type.ManagedFullName} value)");
        sb.AppendLine("    {");
        sb.AppendLine("        _state = ProjectionRuntime.GetOrCreateState(value);");
        if (events.Length > 0)
            sb.AppendLine("        _state.RegisterCleanup(ReleaseSubscriptions);");
        sb.AppendLine("        global::Avalonia.Host.ProjectionDiagnostics.WrapperCreated();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public int GetObjectId(out long value)");
        sb.AppendLine("    {");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            using var call = _state.EnterCall();");
        sb.AppendLine("            value = _state.ObjectId;");
        sb.AppendLine("            return global::Avalonia.Host.HResults.S_OK;");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (global::System.Exception e)");
        sb.AppendLine("        {");
        sb.AppendLine("            value = 0;");
        sb.AppendLine("            return global::System.Runtime.InteropServices.Marshal.GetHRForException(e);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public int GetLifetimeToken(out long value)");
        sb.AppendLine("    {");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            using var call = _state.EnterCall();");
        sb.AppendLine("            value = _state.GetLifetimeToken();");
        sb.AppendLine("            return global::Avalonia.Host.HResults.S_OK;");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (global::System.Exception e)");
        sb.AppendLine("        {");
        sb.AppendLine("            value = 0;");
        sb.AppendLine("            return global::System.Runtime.InteropServices.Marshal.GetHRForException(e);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        foreach (var projected in Lineage(ir, type))
        {
            foreach (var property in projected.Properties)
                EmitImplementationProperty(sb, property);
            foreach (var method in projected.Methods)
                EmitImplementationMethod(sb, method);
            foreach (var @event in projected.Events)
                EmitImplementationEvent(sb, @event);
        }

        if (events.Length > 0)
        {
            sb.AppendLine();
            sb.AppendLine("    private void ReleaseSubscriptions()");
            sb.AppendLine("    {");
            foreach (var @event in events)
            {
                var field = LowerFirst(@event.Name);
                sb.AppendLine($"        foreach (var subscription in _{field}Subscriptions.Values)");
                sb.AppendLine("        {");
                sb.AppendLine("            subscription.Unsubscribe();");
                sb.AppendLine("            global::Avalonia.Host.ProjectionDiagnostics.SubscriptionRemoved();");
                sb.AppendLine("        }");
                sb.AppendLine($"        _{field}Subscriptions.Clear();");
            }
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitEventHandler(ProjectedEvent @event)
    {
        var name = SimpleName(@event.HandlerInterfaceName);
        var ns = NamespaceOf(@event.HandlerInterfaceName);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine("using System.Runtime.InteropServices.Marshalling;");
        if (@event.PayloadKind == EventPayloadKind.Args)
            sb.AppendLine("using System.Linq;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        if (@event.PayloadKind == EventPayloadKind.Args && @event.ArgsInterfaceName is { } argsFullName)
        {
            var argsName = SimpleName(argsFullName);
            var argsIid = @event.ArgsInterfaceIid!;
            // The args interface: one count/getter pair per projected property.
            sb.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]");
            sb.AppendLine($"[Guid(\"{argsIid}\")]");
            sb.AppendLine($"public partial interface {argsName}");
            sb.AppendLine("{");
            foreach (var parameter in @event.Parameters)
            {
                sb.AppendLine("    [PreserveSig]");
                sb.AppendLine($"    int Get{parameter.Name}Count(out int value);");
                sb.AppendLine();
                sb.AppendLine("    [PreserveSig]");
                sb.AppendLine($"    int Get{parameter.Name}At(int index, out AvnVariant value);");
                sb.AppendLine();
            }
            sb.AppendLine("}");
            sb.AppendLine();
            // The host wrapper exposes the CLR event args' collections live.
            sb.AppendLine("[GeneratedComClass]");
            sb.AppendLine($"public sealed partial class {argsName[1..]} : {argsName}");
            sb.AppendLine("{");
            sb.AppendLine($"    private readonly global::System.Collections.IEnumerable?[] _collections = new global::System.Collections.IEnumerable?[{@event.Parameters.Count}];");
            sb.AppendLine();
            sb.AppendLine($"    internal {argsName[1..]}(global::System.Collections.IEnumerable?[] collections) => _collections = collections;");
            sb.AppendLine();
            for (var i = 0; i < @event.Parameters.Count; i++)
            {
                var parameter = @event.Parameters[i];
                sb.AppendLine($"    public int Get{parameter.Name}Count(out int value)");
                sb.AppendLine("    {");
                sb.AppendLine("        value = 0;");
                sb.AppendLine("        try");
                sb.AppendLine("        {");
                sb.AppendLine($"            value = _collections[{i}]?.Cast<object?>().Count() ?? 0;");
                sb.AppendLine("            return global::Avalonia.Host.HResults.S_OK;");
                sb.AppendLine("        }");
                sb.AppendLine("        catch (global::System.Exception e)");
                sb.AppendLine("        {");
                sb.AppendLine("            return global::System.Runtime.InteropServices.Marshal.GetHRForException(e);");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
                sb.AppendLine();
                sb.AppendLine($"    public int Get{parameter.Name}At(int index, out AvnVariant value)");
                sb.AppendLine("    {");
                sb.AppendLine("        value = default;");
                sb.AppendLine("        try");
                sb.AppendLine("        {");
                sb.AppendLine($"            var item = _collections[{i}]?.Cast<object?>().ElementAtOrDefault(index);");
                sb.AppendLine("            if (index < 0 || item is null)");
                sb.AppendLine("                return global::Avalonia.Host.HResults.E_INVALIDARG;");
                sb.AppendLine("            value = AvnVariant.FromObject(item);");
                sb.AppendLine("            return global::Avalonia.Host.HResults.S_OK;");
                sb.AppendLine("        }");
                sb.AppendLine("        catch (global::System.Exception e)");
                sb.AppendLine("        {");
                sb.AppendLine("            return global::System.Runtime.InteropServices.Marshal.GetHRForException(e);");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
                sb.AppendLine();
            }
            sb.AppendLine("}");
            sb.AppendLine();
            // The handler receives the args interface.
            sb.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]");
            sb.AppendLine($"[Guid(\"{@event.HandlerInterfaceIid}\")]");
            sb.AppendLine($"public partial interface {name}");
            sb.AppendLine("{");
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine($"    int Invoke({argsName} args);");
            sb.AppendLine("}");
            return sb.ToString();
        }
        sb.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]");
        sb.AppendLine($"[Guid(\"{@event.HandlerInterfaceIid}\")]");
        sb.AppendLine($"public partial interface {name}");
        sb.AppendLine("{");
        sb.AppendLine("    [PreserveSig]");
        sb.AppendLine($"    int Invoke({string.Join(", ", @event.Parameters.Select(FormatParameter))});");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitRuntime(ProjectionIr ir)
    {
        var classes = ir.Types
            .Where(t => t.Kind == ProjectedTypeKind.Class)
            .OrderByDescending(t => InheritanceDepth(ir, t))
            .ThenBy(t => t.ManagedFullName, StringComparer.Ordinal)
            .ToArray();
        var root = classes.Single(t => t.BaseFullName is null);
        var sb = Header(root);
        sb.AppendLine("internal static class ProjectionRuntime");
        sb.AppendLine("{");
        sb.AppendLine("    private static long s_nextId;");
        sb.AppendLine($"    private static readonly global::System.Runtime.CompilerServices.ConditionalWeakTable<global::Avalonia.AvaloniaObject, {root.Name}> s_wrappers = new();");
        sb.AppendLine("    private static readonly global::System.Runtime.CompilerServices.ConditionalWeakTable<global::Avalonia.AvaloniaObject, global::Avalonia.Host.Ownership.ProjectionObjectState> s_states = new();");
        sb.AppendLine("    private static readonly global::System.Collections.Concurrent.ConcurrentDictionary<long, global::System.WeakReference<global::Avalonia.AvaloniaObject>> s_objects = new();");
        sb.AppendLine();
        sb.AppendLine("    internal static int TrackedObjectIdCount => s_objects.Count;");
        sb.AppendLine();
        sb.AppendLine("    internal static int LiveManagedObjectCount");
        sb.AppendLine("    {");
        sb.AppendLine("        get");
        sb.AppendLine("        {");
        sb.AppendLine("            var count = 0;");
        sb.AppendLine("            foreach (var weak in s_objects.Values)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (weak.TryGetTarget(out _))");
        sb.AppendLine("                    count++;");
        sb.AppendLine("            }");
        sb.AppendLine("            return count;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    internal static global::Avalonia.Host.Ownership.ProjectionObjectState GetOrCreateState(global::Avalonia.AvaloniaObject value) =>");
        sb.AppendLine("        s_states.GetValue(value, CreateState);");
        sb.AppendLine();
        sb.AppendLine("    private static global::Avalonia.Host.Ownership.ProjectionObjectState CreateState(global::Avalonia.AvaloniaObject value)");
        sb.AppendLine("    {");
        sb.AppendLine("        var id = global::System.Threading.Interlocked.Increment(ref s_nextId);");
        sb.AppendLine("        s_objects[id] = new(value);");
        sb.AppendLine("        return new global::Avalonia.Host.Ownership.ProjectionObjectState(value, id);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    internal static void Forget(global::Avalonia.AvaloniaObject value, long objectId)");
        sb.AppendLine("    {");
        sb.AppendLine("        s_wrappers.Remove(value);");
        sb.AppendLine("        s_states.Remove(value);");
        sb.AppendLine("        s_objects.TryRemove(objectId, out _);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    internal static {root.Name}? Wrap(global::Avalonia.AvaloniaObject? value) =>");
        sb.AppendLine("        value is null ? null : s_wrappers.GetValue(value, CreateWrapper);");
        sb.AppendLine();
        sb.AppendLine($"    internal static global::Avalonia.AvaloniaObject? Unwrap({root.Name}? value)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (value is null)");
        sb.AppendLine("            return null;");
        sb.AppendLine("        var hr = value.GetObjectId(out var id);");
        sb.AppendLine("        if (hr < 0)");
        sb.AppendLine("            global::System.Runtime.InteropServices.Marshal.ThrowExceptionForHR(hr);");
        sb.AppendLine("        return s_objects.TryGetValue(id, out var weak) && weak.TryGetTarget(out var result)");
        sb.AppendLine("            ? result");
        sb.AppendLine("            : throw new global::System.ObjectDisposedException($\"Projected Avalonia object {id}\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    private static {root.Name} CreateWrapper(global::Avalonia.AvaloniaObject value) => value switch");
        sb.AppendLine("    {");
        foreach (var type in classes)
            sb.AppendLine($"        global::{type.ManagedFullName} typed => new {type.Name[1..]}(typed),");
        sb.AppendLine("        _ => throw new global::System.NotSupportedException($\"Type '{value.GetType().FullName}' is not in the projection IR\"),");
        sb.AppendLine("    };");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitFactory(ProjectionIr ir)
    {
        var classes = ir.Types
            .Where(t => t.Kind == ProjectedTypeKind.Class && t.IsConstructible)
            .OrderBy(t => t.FullName, StringComparer.Ordinal)
            .ToArray();
        var ns = NamespaceOf(classes[0].FullName)!;
        var factoryFullName = $"{ns}.IAvnControlFactory";
        var sb = Header(classes[0]);
        sb.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]");
        sb.AppendLine($"[Guid(\"{ir.FactoryIid ?? ClrTypeExtractor.CreateDeterministicIid(factoryFullName)}\")]");
        sb.AppendLine("public partial interface IAvnControlFactory");
        sb.AppendLine("{");
        foreach (var type in classes)
        {
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine($"    int Create{type.Name[4..]}(out {type.Name}? value);");
            sb.AppendLine();
        }
        foreach (var statics in ir.AttachedProperties
                     .GroupBy(p => p.StaticsInterfaceName, StringComparer.Ordinal)
                     .OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var interfaceName = SimpleName(statics.Key);
            var ownerName = statics.First().OwnerName;
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine($"    int Get{ownerName}Statics(out {interfaceName}? value);");
            sb.AppendLine();
        }
        if (ir.BrushInterfaceName is { } brushInterfaceName)
        {
            var brushName = SimpleName(brushInterfaceName);
            var colorAbiName = GeometryMarshalling.All
                .Single(geometry => geometry.Kind == MarshallingKind.Color).AbiName;
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine(
                $"    int {BrushMarshalling.FactoryMethodName}({colorAbiName} color, double opacity, out {brushName}? value);");
            sb.AppendLine();
        }
        if (ir.GradientBrushInterfaceName is not null)
        {
            var linearName = SimpleName(ir.LinearGradientBrushInterfaceName!);
            var radialName = SimpleName(ir.RadialGradientBrushInterfaceName!);
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine(
                $"    int {GradientBrushMarshalling.CreateLinearFactoryMethodName}(double opacity, int spreadMethod, int stopCount, AvnGradientStopBuffer stops, AvnRelativePoint startPoint, AvnRelativePoint endPoint, out {linearName}? value);");
            sb.AppendLine();
            sb.AppendLine("    [PreserveSig]");
            sb.AppendLine(
                $"    int {GradientBrushMarshalling.CreateRadialFactoryMethodName}(double opacity, int spreadMethod, int stopCount, AvnGradientStopBuffer stops, AvnRelativePoint center, AvnRelativePoint gradientOrigin, AvnRelativeScalar radiusX, AvnRelativeScalar radiusY, out {radialName}? value);");
            sb.AppendLine();
        }
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("[GeneratedComClass]");
        sb.AppendLine("public sealed partial class AvnControlFactory : IAvnControlFactory");
        sb.AppendLine("{");
        foreach (var type in classes)
        {
            var shortName = type.Name[4..];
            sb.AppendLine($"    public int Create{shortName}(out {type.Name}? value)");
            sb.AppendLine("    {");
            sb.AppendLine("        value = null;");
            sb.AppendLine("        try");
            sb.AppendLine("        {");
            sb.AppendLine("            global::Avalonia.Threading.Dispatcher.UIThread.VerifyAccess();");
            sb.AppendLine($"            value = ({type.Name})ProjectionRuntime.Wrap(new global::{type.ManagedFullName}())!;");
            sb.AppendLine("            return global::Avalonia.Host.HResults.S_OK;");
            sb.AppendLine("        }");
            sb.AppendLine("        catch (global::System.Exception e)");
            sb.AppendLine("        {");
            sb.AppendLine("            return global::System.Runtime.InteropServices.Marshal.GetHRForException(e);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        foreach (var statics in ir.AttachedProperties
                     .GroupBy(p => p.StaticsInterfaceName, StringComparer.Ordinal)
                     .OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var interfaceName = SimpleName(statics.Key);
            var ownerName = statics.First().OwnerName;
            sb.AppendLine($"    public int Get{ownerName}Statics(out {interfaceName}? value)");
            sb.AppendLine("    {");
            sb.AppendLine($"        value = new {interfaceName[1..]}();");
            sb.AppendLine("        return global::Avalonia.Host.HResults.S_OK;");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        if (ir.BrushInterfaceName is { } factoryBrushInterfaceName)
        {
            var brushName = SimpleName(factoryBrushInterfaceName);
            var colorAbiName = GeometryMarshalling.All
                .Single(geometry => geometry.Kind == MarshallingKind.Color).AbiName;
            // A brush carries no dispatcher affinity, so unlike a control it needs no UI thread.
            sb.AppendLine(
                $"    public int {BrushMarshalling.FactoryMethodName}({colorAbiName} color, double opacity, out {brushName}? value)");
            sb.AppendLine("    {");
            sb.AppendLine($"        value = new {brushName[1..]}(color, opacity);");
            sb.AppendLine("        return global::Avalonia.Host.HResults.S_OK;");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        if (ir.GradientBrushInterfaceName is not null)
        {
            var linearName = SimpleName(ir.LinearGradientBrushInterfaceName!);
            var radialName = SimpleName(ir.RadialGradientBrushInterfaceName!);
            sb.AppendLine(
                $"    public int {GradientBrushMarshalling.CreateLinearFactoryMethodName}(double opacity, int spreadMethod, int stopCount, AvnGradientStopBuffer stops, AvnRelativePoint startPoint, AvnRelativePoint endPoint, out {linearName}? value)");
            sb.AppendLine("    {");
            sb.AppendLine("        value = null;");
            sb.AppendLine($"        if (stopCount < 0 || stopCount > {GradientBrushMarshalling.MaxStops})");
            sb.AppendLine("            return global::Avalonia.Host.HResults.E_INVALIDARG;");
            sb.AppendLine($"        value = new {linearName[1..]}(opacity, spreadMethod, stopCount, stops, startPoint, endPoint);");
            sb.AppendLine("        return global::Avalonia.Host.HResults.S_OK;");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine(
                $"    public int {GradientBrushMarshalling.CreateRadialFactoryMethodName}(double opacity, int spreadMethod, int stopCount, AvnGradientStopBuffer stops, AvnRelativePoint center, AvnRelativePoint gradientOrigin, AvnRelativeScalar radiusX, AvnRelativeScalar radiusY, out {radialName}? value)");
            sb.AppendLine("    {");
            sb.AppendLine("        value = null;");
            sb.AppendLine($"        if (stopCount < 0 || stopCount > {GradientBrushMarshalling.MaxStops})");
