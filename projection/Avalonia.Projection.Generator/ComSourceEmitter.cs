    public static string EmitCollection(ProjectionIr ir, ProjectedProperty collection)
    {
        var root = ir.Types.Single(t => t.Kind == ProjectedTypeKind.Class && t.BaseFullName is null);
        var interfaceName = SimpleName(collection.InterfaceName!);
        var className = interfaceName[1..];
        var elementKind = collection.ElementKind
            ?? throw new InvalidOperationException($"Collection '{interfaceName}' has no element kind.");
        var elementName = CSharpType(elementKind, collection.ElementInterfaceName, false);
        var managedElementName = elementKind == MarshallingKind.ComInterface
            ? ir.Types.Single(t => t.FullName == collection.ElementInterfaceName).ManagedFullName
            : null;
        var readElement = elementKind switch
        {
            MarshallingKind.ComInterface =>
                $"({elementName})ProjectionRuntime.Wrap((global::{managedElementName})_value[index]!)",
            _ => "_value[index]",
        };
        var writeElement = elementKind switch
        {
            MarshallingKind.ComInterface =>
                $"(global::{managedElementName})ProjectionRuntime.Unwrap(value)!",
            _ => "value",
        };
        var sb = Header(root);
        sb.AppendLine("[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16)]");
        sb.AppendLine($"[Guid(\"{collection.InterfaceIid}\")]");
        sb.AppendLine($"public partial interface {interfaceName}");
        sb.AppendLine("{");
        sb.AppendLine("    [PreserveSig]");
        sb.AppendLine("    int GetCount(out int value);");
        sb.AppendLine();
        sb.AppendLine("    [PreserveSig]");
        sb.AppendLine($"    int GetAt(int index, out {elementName} value);");
        sb.AppendLine();
        sb.AppendLine("    [PreserveSig]");
        sb.AppendLine($"    int Add({elementName} value);");
        sb.AppendLine();
        sb.AppendLine("    [PreserveSig]");
        sb.AppendLine($"    int IndexOf({elementName} value, out int index);");
        sb.AppendLine();
        sb.AppendLine("    [PreserveSig]");
        sb.AppendLine("    int RemoveAt(int index);");
        sb.AppendLine();
        sb.AppendLine("    [PreserveSig]");
        sb.AppendLine("    int Clear();");
        sb.AppendLine("}");
        var managedCollectionName = CSharpManagedTypeName(collection.ManagedTypeName);
        if (collection.HostImplementationTypeName is { } hostType)
        {
            // A host-implemented collection: the interface is generated here; the
            // class lives in the host assembly and owns the adaptation semantics.
            // The marshal signatures are typed object? so every member sharing
            // the interface can route through it regardless of CLR collection type.
            sb.AppendLine();
            sb.AppendLine($"public static class {interfaceName[1..]}Marshal");
            sb.AppendLine("{");
            sb.AppendLine($"    public static {interfaceName}? FromManaged(object? value) =>");
            sb.AppendLine($"        value is null ? null : {hostType}.FromManaged(value);");
            sb.AppendLine();
            sb.AppendLine($"    public static object? ToManaged({interfaceName}? value) =>");
            sb.AppendLine($"        {hostType}.ToManaged(value);");
            sb.AppendLine("}");
            sb.AppendLine();
            return sb.ToString().TrimEnd() + Environment.NewLine;
        }
        sb.AppendLine("[GeneratedComClass]");
        sb.AppendLine($"public sealed partial class {className} : {interfaceName}");
        sb.AppendLine("{");
        sb.AppendLine($"    private readonly global::{managedCollectionName} _value;");
        sb.AppendLine();
        sb.AppendLine($"    internal {className}(global::{managedCollectionName} value) => _value = value;");
        sb.AppendLine();
        sb.AppendLine($"    public static {interfaceName}? FromManaged(global::{managedCollectionName}? value) =>");
        sb.AppendLine($"        value is null ? null : new {className}(value);");
        sb.AppendLine();
        sb.AppendLine($"    public static global::{managedCollectionName}? ToManaged({interfaceName}? value) =>");
        sb.AppendLine($"        value is {className} local ? local._value : null;");
        EmitCollectionMethod(
            sb,
            "GetCount",
            "out int value",
            "value = _value.Count;",
            initializeOut: "value = 0;");
        EmitCollectionMethod(
            sb,
            "GetAt",
            $"int index, out {elementName} value",
            $"value = {readElement};",
            initializeOut: elementKind == MarshallingKind.StringUtf16
                ? "value = string.Empty;"
                : "value = null;");
        EmitCollectionMethod(
            sb,
            "Add",
            $"{elementName} value",
            $"_value.Add({writeElement});");
        EmitCollectionMethod(
            sb,
            "IndexOf",
            $"{elementName} value, out int index",
            $"index = _value.IndexOf({writeElement});",
            initializeOut: "index = -1;");
        EmitCollectionMethod(sb, "RemoveAt", "int index", "_value.RemoveAt(index);");
        EmitCollectionMethod(sb, "Clear", "", "_value.Clear();");
        sb.AppendLine("}");
        return sb.ToString();
    }

