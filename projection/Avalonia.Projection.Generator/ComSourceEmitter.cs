    private static void EmitImplementationEvent(StringBuilder sb, ProjectedEvent @event)
    {
        var name = @event.Name;
        var field = LowerFirst(name);
        var handler = SimpleName(@event.HandlerInterfaceName);
        sb.AppendLine();
        sb.AppendLine($"    public int Advise{name}({handler}? handler, out long subscriptionId)");
        sb.AppendLine("    {");
        sb.AppendLine("        subscriptionId = 0;");
        sb.AppendLine("        if (handler is null)");
        sb.AppendLine("            return global::Avalonia.Host.HResults.E_POINTER;");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            using var call = _state.EnterCall();");
        sb.AppendLine("            _value.VerifyAccess();");
        sb.AppendLine("            var eventSource = _value;");
        sb.AppendLine($"            var callback = new global::{@event.ManagedHandlerTypeName}((_, eventArgs) =>");
        sb.AppendLine("            {");
        if (@event.PayloadKind == EventPayloadKind.Args && @event.ArgsInterfaceName is { } argsFullName)
        {
            var argsName = SimpleName(argsFullName);
            sb.AppendLine($"                var args = new {argsName[1..]}(new global::System.Collections.IEnumerable?[]");
            sb.Append("                {");
            sb.Append(string.Join(", ", @event.Parameters.Select(p => $"eventArgs.{p.Name}")));
            sb.AppendLine("});");
            sb.AppendLine("                var hr = handler.Invoke(args);");
            sb.AppendLine("                if (hr < 0)");
            sb.AppendLine("                    global::System.Runtime.InteropServices.Marshal.ThrowExceptionForHR(hr);");
        }
        else
        {
            foreach (var parameter in @event.Parameters.Where(p => p.Direction == ParameterDirection.InOut))
                sb.AppendLine($"                var {LowerFirst(parameter.Name)} = {EventReadExpression(parameter)};");
            var arguments = string.Join(", ", @event.Parameters.Select(parameter =>
                parameter.Direction == ParameterDirection.InOut
                    ? $"ref {LowerFirst(parameter.Name)}"
                    : EventReadExpression(parameter)));
            sb.AppendLine($"                var hr = handler.Invoke({arguments});");
            sb.AppendLine("                if (hr < 0)");
            sb.AppendLine("                    global::System.Runtime.InteropServices.Marshal.ThrowExceptionForHR(hr);");
            foreach (var parameter in @event.Parameters.Where(p => p.Direction == ParameterDirection.InOut))
                sb.AppendLine($"                eventArgs.{parameter.Name} = {EventWriteExpression(parameter, LowerFirst(parameter.Name))};");
        }
        sb.AppendLine("            });");
        sb.AppendLine($"            eventSource.{name} += callback;");
        sb.AppendLine($"            subscriptionId = global::System.Threading.Interlocked.Increment(ref _next{name}SubscriptionId);");
        sb.AppendLine($"            _{field}Subscriptions.Add(subscriptionId, (handler, () => eventSource.{name} -= callback));");
        sb.AppendLine("            global::Avalonia.Host.ProjectionDiagnostics.SubscriptionAdded();");
        sb.AppendLine("            return global::Avalonia.Host.HResults.S_OK;");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (global::System.Exception e)");
        sb.AppendLine("        {");
        sb.AppendLine("            return global::System.Runtime.InteropServices.Marshal.GetHRForException(e);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public int Unadvise{name}(long subscriptionId)");
        sb.AppendLine("    {");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            using var call = _state.EnterCall();");
        sb.AppendLine("            _value.VerifyAccess();");
        sb.AppendLine($"            if (!_{field}Subscriptions.Remove(subscriptionId, out var subscription))");
        sb.AppendLine("                return global::Avalonia.Host.HResults.E_INVALIDARG;");
        sb.AppendLine("            subscription.Unsubscribe();");
        sb.AppendLine("            global::Avalonia.Host.ProjectionDiagnostics.SubscriptionRemoved();");
        sb.AppendLine("            return global::Avalonia.Host.HResults.S_OK;");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (global::System.Exception e)");
        sb.AppendLine("        {");
        sb.AppendLine("            return global::System.Runtime.InteropServices.Marshal.GetHRForException(e);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private static string ReadExpression(ProjectedProperty property) =>
        property.Kind switch
        {
            MarshallingKind.I32 when property.ManagedTypeName is not "System.Int32" =>
                $"(int)_value.{property.Name}",
            MarshallingKind.StringUtf16 when property.StringConverterTypeName is { } converter =>
                property.IsNullable
                    ? $"global::{converter}.ToAbi(_value.{property.Name})"
                    // The converter encodes null as a null string, but the ABI member
                    // is non-nullable; the property's value is always encodable.
                    : $"global::{converter}.ToAbi(_value.{property.Name})!",
            MarshallingKind.StringUtf16 when property.ManagedTypeName is not "System.String" =>
                property.IsNullable
                    ? $"_value.{property.Name}?.ToString()"
                    : $"_value.{property.Name}.ToString()",
            MarshallingKind.CharUtf16 => $"(ushort)_value.{property.Name}",
            MarshallingKind.TimeSpanI64 => $"_value.{property.Name}.Ticks",
            MarshallingKind.DateTimeI64 => $"_value.{property.Name}.Ticks",
            MarshallingKind.PixelPointI32 => $"AvnPixelPoint.FromAvalonia(_value.{property.Name})",
            MarshallingKind.Bool => $"_value.{property.Name} ? 1 : 0",
            MarshallingKind.NullableBool =>
                $"!_value.{property.Name}.HasValue ? -1 : _value.{property.Name}.Value ? 1 : 0",
            MarshallingKind.ComInterface =>
                $"({SimpleName(property.InterfaceName!)}?)ProjectionRuntime.Wrap(_value.{property.Name} as global::Avalonia.AvaloniaObject)",
            MarshallingKind.Brush =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromBrush(_value.{property.Name})",
            MarshallingKind.Command =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromCommand(_value.{property.Name})",
            MarshallingKind.DataTemplate =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromTemplate(_value.{property.Name})",
            MarshallingKind.ItemFilter =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromPredicate(_value.{property.Name})",
            MarshallingKind.TextFilter =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromPredicate(_value.{property.Name})",
            MarshallingKind.ItemSelector =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromSelector(_value.{property.Name})",
            MarshallingKind.TextSelector =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromSelector(_value.{property.Name})",
            MarshallingKind.PopupPlacement =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromCallback(_value.{property.Name})",
            MarshallingKind.AsyncPopulator =>
                $"{SimpleName(property.InterfaceName!)[1..]}.FromPopulator(_value.{property.Name})",
            MarshallingKind.Variant => $"AvnVariant.FromObject(_value.{property.Name})",
            MarshallingKind.ComCollection =>
                property.HostImplementationTypeName is { }
                    ? $"{SimpleName(property.InterfaceName!)[1..]}Marshal.FromManaged(_value.{property.Name})"
                    : $"{SimpleName(property.InterfaceName!)[1..]}.FromManaged(_value.{property.Name})",
            _ when GeometryMarshalling.TryGet(property.Kind, out var geometry) =>
                $"{(property.IsNullable ? geometry.OptionalAbiName : geometry.AbiName)}.FromAvalonia(_value.{property.Name})",
            _ => $"_value.{property.Name}",
        };

    private static string EventReadExpression(ProjectedParameter parameter) =>
        parameter.Kind switch
        {
            MarshallingKind.I32 when parameter.ManagedTypeName is not "System.Int32" =>
                $"(int)eventArgs.{parameter.Name}",
            MarshallingKind.Bool => $"eventArgs.{parameter.Name} ? 1 : 0",
            MarshallingKind.NullableBool =>
                $"!eventArgs.{parameter.Name}.HasValue ? -1 : eventArgs.{parameter.Name}.Value ? 1 : 0",
            MarshallingKind.Variant => $"AvnVariant.FromObject(eventArgs.{parameter.Name})",
            // A StringUtf16 event field whose CLR type is not string converts through the
            // host-side converter named by the projection (decimal? rides AvnDecimal).
            MarshallingKind.StringUtf16 when parameter.StringConverterTypeName is { } converter =>
                $"global::{converter}.ToAbi(eventArgs.{parameter.Name})",
            _ when GeometryMarshalling.TryGet(parameter.Kind, out var geometry) =>
                $"{geometry.AbiName}.FromAvalonia(eventArgs.{parameter.Name})",
            MarshallingKind.DateTimeI64 when parameter.IsNullable &&
                parameter.ManagedTypeName?.Contains("System.DateTimeOffset") == true =>
                $"eventArgs.{parameter.Name}.HasValue ? AvnOptionalDateTime.FromDateTime(eventArgs.{parameter.Name}.Value.UtcDateTime) : default",
            MarshallingKind.DateTimeI64 when parameter.IsNullable =>
                $"AvnOptionalDateTime.FromDateTime(eventArgs.{parameter.Name})",
            MarshallingKind.DateTimeI64 when parameter.ManagedTypeName?.Contains("System.DateTimeOffset") == true =>
                $"eventArgs.{parameter.Name}.UtcDateTime.Ticks",
            MarshallingKind.DateTimeI64 => $"eventArgs.{parameter.Name}.Ticks",
            MarshallingKind.TimeSpanI64 when parameter.IsNullable =>
                $"AvnOptionalTimeSpan.FromTimeSpan(eventArgs.{parameter.Name})",
            MarshallingKind.TimeSpanI64 => $"eventArgs.{parameter.Name}.Ticks",
            _ => $"eventArgs.{parameter.Name}",
        };

    private static string EventWriteExpression(ProjectedParameter parameter, string value) =>
        parameter.Kind switch
        {
            MarshallingKind.I32 when parameter.ManagedTypeName is not "System.Int32" =>
                $"(global::{parameter.ManagedTypeName}){value}",
            MarshallingKind.StringUtf16 when parameter.StringConverterTypeName is { } writeConverter =>
                $"global::{writeConverter}.FromAbi({value})",
            MarshallingKind.Bool => $"{value} != 0",
            MarshallingKind.NullableBool =>
                $"{value} switch {{ -1 => null, 0 => false, 1 => true, _ => throw new global::System.ArgumentOutOfRangeException(nameof({value})) }}",
            _ when GeometryMarshalling.IsGeometry(parameter.Kind) => $"{value}.ToAvalonia()",
            MarshallingKind.DateTimeI64 when parameter.IsNullable => $"{value}.ToDateTime()",
            MarshallingKind.TimeSpanI64 when parameter.IsNullable => $"{value}.ToTimeSpan()",
            _ => value,
        };

    private static string WriteExpression(ProjectedProperty property) =>
        property.Kind switch
        {
            MarshallingKind.I32 when property.ManagedTypeName is not "System.Int32" =>
                $"(global::{property.ManagedTypeName})value",
            MarshallingKind.StringUtf16 when property.StringConverterTypeName is { } converter =>
                property.IsNullable
                    ? $"global::{converter}.FromAbi(value)"
                    // A null ABI value for a non-nullable managed property is a caller
                    // contract violation; the converter would surface it as null anyway.
                    : $"global::{converter}.FromAbi(value)!",
            MarshallingKind.StringUtf16 when property.ManagedTypeName is not "System.String" =>
                property.IsNullable
                    ? $"value is null ? null : global::{property.ManagedTypeName}.Parse(value)"
                    : $"global::{property.ManagedTypeName}.Parse(value)",
            MarshallingKind.CharUtf16 => "(char)value",
            MarshallingKind.TimeSpanI64 => "global::System.TimeSpan.FromTicks(value)",
            MarshallingKind.DateTimeI64 => "new global::System.DateTime(value, global::System.DateTimeKind.Utc)",
            MarshallingKind.PixelPointI32 => "value.ToAvalonia()",
            MarshallingKind.Bool => "value != 0",
            MarshallingKind.NullableBool =>
                "value switch { -1 => null, 0 => false, 1 => true, _ => throw new global::System.ArgumentOutOfRangeException(nameof(value)) }",
            MarshallingKind.ComInterface =>
                $"(global::{property.ManagedTypeName})ProjectionRuntime.Unwrap(value)!",
            MarshallingKind.Brush => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToBrush(value)", property),
            MarshallingKind.Command => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToCommand(value)", property),
            MarshallingKind.DataTemplate => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToTemplate(value)", property),
            MarshallingKind.ItemFilter => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToPredicate(value)", property),
            MarshallingKind.TextFilter => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToPredicate(value)", property),
            MarshallingKind.ItemSelector => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToSelector(value)", property),
            MarshallingKind.TextSelector => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToSelector(value)", property),
            MarshallingKind.PopupPlacement => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToCallback(value)", property),
            MarshallingKind.AsyncPopulator => NullForgiving($"{SimpleName(property.InterfaceName!)[1..]}.ToPopulator(value)", property),
            MarshallingKind.Variant => "value.ToObject()",
            MarshallingKind.ComCollection => property.HostImplementationTypeName is { }
                ? $"(global::{CSharpManagedTypeName(property.ManagedTypeName)}?)({SimpleName(property.InterfaceName!)[1..]}Marshal.ToManaged(value))!"
                : $"{SimpleName(property.InterfaceName!)[1..]}.ToManaged(value)",
            _ when GeometryMarshalling.IsGeometry(property.Kind) => "value.ToAvalonia()",
            _ => "value",
        };

    /// <summary>
    /// The initializer for a getter's out parameter: reference-typed ABI values are
    /// nullable and initialize to null, while a non-nullable ABI string initializes to
    /// the empty string so the catch path never reports an uninitialized value.
    /// </summary>
    private static string OutInitializer(ProjectedProperty property, string type) =>
        property.Kind == MarshallingKind.StringUtf16 && !property.IsNullable
            ? "value = string.Empty;"
            : "value = default;";

    /// <summary>
    /// The To* marshalers all return nullable managed values, but a non-nullable
    /// managed property rejects null; a null ABI value for such a property is a caller
    /// contract violation, so the assignment carries the null-forgiving operator.
    /// </summary>
    private static string NullForgiving(string expression, ProjectedProperty property) =>
        property.IsNullable ? expression : expression + "!";

    private static string MethodReturnExpression(ProjectedParameter output, string call) =>
        output.Kind switch
        {
            MarshallingKind.I32 when output.ManagedTypeName is not "System.Int32" => $"(int){call}",
            MarshallingKind.Bool => $"{call} ? 1 : 0",
            MarshallingKind.ComInterface =>
                $"({SimpleName(output.InterfaceName!)}?)ProjectionRuntime.Wrap({call} as global::Avalonia.AvaloniaObject)",
            MarshallingKind.Variant => $"AvnVariant.FromObject({call})",
            MarshallingKind.Brush =>
                $"{SimpleName(output.InterfaceName!)[1..]}.FromBrush({call})",
            MarshallingKind.Command =>
                $"{SimpleName(output.InterfaceName!)[1..]}.FromCommand({call})",
            MarshallingKind.TimeSpanI64 => $"{call}.Ticks",
            MarshallingKind.PixelPointI32 => $"AvnPixelPoint.FromAvalonia({call})",
            _ => call,
        };

    private static string MethodArgument(ProjectedParameter parameter) =>
        parameter.Kind switch
        {
            MarshallingKind.I32 when parameter.ManagedTypeName is not "System.Int32" =>
                $"(global::{parameter.ManagedTypeName}){parameter.Name}",
            MarshallingKind.Bool => $"{parameter.Name} != 0",
            MarshallingKind.NullableBool =>
                $"{parameter.Name} switch {{ -1 => null, 0 => false, 1 => true, _ => throw new global::System.ArgumentOutOfRangeException(nameof({parameter.Name})) }}",
            MarshallingKind.ComInterface =>
                $"(global::{parameter.ManagedTypeName})ProjectionRuntime.Unwrap({parameter.Name})!",
            MarshallingKind.Variant => parameter.IsNullable
                ? $"{parameter.Name}.ToObject()"
                // A null variant for a parameter the managed API demands non-null is a
                // caller contract violation; the null-forgiving operator documents it.
                : $"{parameter.Name}.ToObject()!",
            MarshallingKind.Notification => parameter.IsNullable
                ? $"{SimpleName(parameter.InterfaceName!)[1..]}.ToNotification({parameter.Name})"
                // The managed API demands a non-null notification; a null ABI value is
                // a caller contract violation.
                : $"{SimpleName(parameter.InterfaceName!)[1..]}.ToNotification({parameter.Name})!",
            _ when GeometryMarshalling.IsGeometry(parameter.Kind) => $"{parameter.Name}.ToAvalonia()",
            _ => parameter.Name,
        };

    private static IEnumerable<ProjectedType> Lineage(ProjectionIr ir, ProjectedType type)
    {
        var byName = ir.Types.ToDictionary(t => t.FullName, StringComparer.Ordinal);
        var stack = new Stack<ProjectedType>();
        for (var current = type; ; current = byName[current.BaseFullName])
        {
            stack.Push(current);
            if (current.BaseFullName is null)
                break;
        }
        return stack;
    }

    private static int InheritanceDepth(ProjectionIr ir, ProjectedType type)
    {
        var byName = ir.Types.ToDictionary(t => t.FullName, StringComparer.Ordinal);
        var result = 0;
        while (type.BaseFullName is { } baseName)
        {
            result++;
            type = byName[baseName];
        }
        return result;
    }

    private static string FormatParameter(ProjectedParameter p)
    {
        var prefix = p.Direction switch
        {
            ParameterDirection.Out => "out ",
            ParameterDirection.InOut => "ref ",
            _ => "",
        };
        // Out parameters initialize to default before the call, so a nullable ABI
        // value must stay nullable even in the out direction; the always-nullable
        // reference kinds ignore this flag entirely.
        var ty = CSharpType(p.Kind, p.InterfaceName, p.IsNullable);
        return $"{prefix}{ty} {p.Name}";
    }

    /// <summary>
    /// The ABI type of an attached property. Attached properties are always non-generic scalars
    /// or strings; a nullable one is a string that may be absent.
    /// </summary>
    private static string AttachedCSharpType(ProjectedAttachedProperty property) =>
        CSharpType(property.Kind, null, property.IsNullable);

    /// <summary>
    /// The ABI-side C# type for a member. Reference-typed ABI values (interfaces,
    /// collections, adapters) are always emitted as nullable: a null reference is a
    /// valid ABI value meaning "absent", independently of the managed member's
    /// nullability, and the From* marshalers all return nullable references.
    /// </summary>
    private static string CSharpType(MarshallingKind kind, string? interfaceName, bool nullable) =>
        kind switch
        {
            MarshallingKind.Void => "void",
            MarshallingKind.I32 => "int",
            MarshallingKind.I64 => "long",
            MarshallingKind.F32 => "float",
            MarshallingKind.F64 => "double",
            MarshallingKind.CharUtf16 => "ushort",
            MarshallingKind.Bool => "int",
            MarshallingKind.NullableBool => "int",
            MarshallingKind.StringUtf16 => nullable ? "string?" : "string",
            MarshallingKind.Variant => "AvnVariant",
            MarshallingKind.TimeSpanI64 => nullable ? "AvnOptionalTimeSpan" : "long",
            MarshallingKind.DateTimeI64 => nullable ? "AvnOptionalDateTime" : "long",
            MarshallingKind.PixelPointI32 => "AvnPixelPoint",
            MarshallingKind.ComInterface => (interfaceName is null ? "object?" : SimpleName(interfaceName) + "?"),
            MarshallingKind.Brush => SimpleName(interfaceName!) + "?",
            MarshallingKind.Command => SimpleName(interfaceName!) + "?",
            MarshallingKind.DataTemplate => SimpleName(interfaceName!) + "?",
            MarshallingKind.ItemFilter => SimpleName(interfaceName!) + "?",
            MarshallingKind.TextFilter => SimpleName(interfaceName!) + "?",
            MarshallingKind.ItemSelector => SimpleName(interfaceName!) + "?",
            MarshallingKind.TextSelector => SimpleName(interfaceName!) + "?",
            MarshallingKind.PopupPlacement => SimpleName(interfaceName!) + "?",
            MarshallingKind.AsyncPopulator => SimpleName(interfaceName!) + "?",
            MarshallingKind.Notification => SimpleName(interfaceName!) + "?",
            MarshallingKind.ComCollection => SimpleName(interfaceName!) + "?",
            _ when GeometryMarshalling.TryGet(kind, out var geometry) =>
                nullable ? geometry.OptionalAbiName : geometry.AbiName,
            _ => throw new InvalidOperationException($"Cannot emit C# for {kind}"),
        };

    private static string FieldType(GeometryFieldKind kind) =>
        kind switch
        {
            GeometryFieldKind.Double => "double",
            GeometryFieldKind.UInt32 => "uint",
            _ => throw new InvalidOperationException($"Cannot emit C# for field kind {kind}"),
        };

    private static string? NamespaceOf(string fullName)
    {
        var i = fullName.LastIndexOf('.');
        return i < 0 ? null : fullName[..i];
    }

    /// <summary>
    /// CLR <see cref="Type.FullName"/> for a constructed generic uses backticks
    /// (<c>AvaloniaList`1[[T, Assembly, ...]]</c>). C# needs
    /// <c>AvaloniaList&lt;T&gt;</c>.
    /// </summary>
    private static string CSharpManagedTypeName(string? fullName)
    {
        if (string.IsNullOrEmpty(fullName))
            return fullName ?? "";

        var nullable = fullName.EndsWith('?');
        var name = nullable ? fullName[..^1] : fullName;
        var tick = name.IndexOf('`');
        if (tick < 0)
            return fullName;

        var definition = name[..tick];
        var start = name.IndexOf("[[", tick, StringComparison.Ordinal);
        if (start < 0)
            return definition + (nullable ? "?" : "");

        var inner = name[(start + 2)..];
        var comma = inner.IndexOf(',');
        var argument = comma < 0 ? inner.TrimEnd(']') : inner[..comma];
        var rewritten = $"{definition}<{argument}>";
        return nullable ? rewritten + "?" : rewritten;
    }

    private static string SimpleName(string fullName)
    {
        var i = fullName.LastIndexOf('.');
        return i < 0 ? fullName : fullName[(i + 1)..];
    }

    private static string LowerFirst(string value) =>
        char.ToLowerInvariant(value[0]) + value[1..];
